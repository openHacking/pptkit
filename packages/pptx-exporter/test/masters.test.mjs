import assert from 'node:assert/strict';
import test from 'node:test';
import { createPresentation } from '@pptkit/core';
import { generatePptx } from '../dist/index.js';
import { readGeneratedZip } from '../../../tests/support/read-generated-zip.mjs';
import { multiMasterDocument } from '../../../tests/fixtures/multi-master.mjs';

test('native masters own separate themes/backgrounds and bidirectional layout relationships with global unique layout ids', async () => {
  const result = await generatePptx(multiMasterDocument(createPresentation)); assert.deepEqual(result.warnings, []);
  const p = readGeneratedZip(result.bytes), xml = name => p.get('ppt/' + name).toString();
  assert.equal((xml('presentation.xml').match(/<p:sldMasterId /g) ?? []).length, 4);
  for (const [part, theme] of [[2, 3], [3, 4], [4, 5]]) {
    assert.match(xml(`slideMasters/_rels/slideMaster${part}.xml.rels`), new RegExp(`Target="../theme/theme${theme}.xml"`));
    assert.ok(p.get('[Content_Types].xml').toString().includes(`/ppt/slideMasters/slideMaster${part}.xml`));
  }
  assert.match(xml('slideMasters/slideMaster2.xml'), /name="Red &amp; one"/); assert.match(xml('slideMasters/slideMaster2.xml'), /<p:bg>/);
  assert.doesNotMatch(xml('slideLayouts/slideLayout2.xml'), /<p:bg>/);
  for (const [layout, master] of [[1, 1], [2, 2], [3, 3], [4, 2], [5, 1]]) assert.match(xml(`slideLayouts/_rels/slideLayout${layout}.xml.rels`), new RegExp(`Target="../slideMasters/slideMaster${master}.xml"`));
  const ids = [1, 2, 3, 4].flatMap(i => [...xml(`slideMasters/slideMaster${i}.xml`).matchAll(/<p:sldLayoutId id="(\d+)"/g)].map(m => m[1])); assert.equal(ids.length, 5); assert.equal(new Set(ids).size, 5);
  const masterIds = [...xml('presentation.xml').matchAll(/<p:sldMasterId id="(\d+)"/g)].map(m => m[1]);
  assert.equal(new Set([...masterIds, ...ids]).size, masterIds.length + ids.length, 'PowerPoint master/layout IDs must not collide');
  assert.doesNotMatch(xml('slideMasters/slideMaster4.xml'), /<p:sldLayoutIdLst>/); assert.match(xml('slideMasters/slideMaster4.xml'), /preserve="1"/);
  assert.match(xml('theme/theme3.xml'), /CC2200/); assert.match(xml('theme/theme4.xml'), /0044CC/);
  assert.match(xml('notesMasters/_rels/notesMaster1.xml.rels'), /theme2.xml/); assert.match(xml('theme/theme2.xml'), /112233/);
});

test('empty master registry retains legacy generated bytes', async () => {
  const generate = async masters => { const d = createPresentation({ id: 'legacy', ...(masters === undefined ? {} : { masters }) }); d.addSlide({ id: 'page' }); return (await generatePptx(d)).bytes; };
  assert.deepEqual(await generate([]), await generate(undefined));
});

test('master IDs are allocated after the entire layout range, including many unused/interleaved layouts', async () => {
  const d = createPresentation({ masters: [{ id: 'a', name: 'A' }, { id: 'b', name: 'B' }] });
  for (let i = 0; i < 24; i++) d.defineSlideLayout({ id: 'l' + i, name: 'L' + i, masterId: i % 2 ? 'a' : 'b' });
  d.addSlide({ layoutId: 'l0' });
  const parts = readGeneratedZip((await generatePptx(d)).bytes);
  const masterIds = [...parts.get('ppt/presentation.xml').toString().matchAll(/<p:sldMasterId id="(\d+)"/g)].map(m => Number(m[1]));
  const layouts = [...parts].filter(([p]) => /^ppt\/slideMasters\/slideMaster\d+.xml$/.test(p)).flatMap(([, b]) => [...b.toString().matchAll(/<p:sldLayoutId id="(\d+)"/g)].map(m => Number(m[1])));
  assert.equal(layouts.length, 25); assert.equal(new Set([...masterIds, ...layouts]).size, 28);
  assert.ok(masterIds.slice(1).every(id => id > Math.max(...layouts)));
});
