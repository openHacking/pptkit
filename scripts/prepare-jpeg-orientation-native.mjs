import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { createPresentation } from '../packages/core/dist/index.js';
import { generatePptx, inspectJpegExifOrientation } from '../packages/pptx-exporter/dist/index.js';
import { renderPresentationToSvg } from '../packages/svg-renderer/dist/index.js';
const dir=process.argv[2]; if(!dir || process.argv.length!==3) throw Error('Expected sample directory.');
const jpeg=await readFile(join(dir,'orientation6.jpg')), png=await readFile(join(dir,'normalized.png'));
const info=inspectJpegExifOrientation(jpeg); if(info.orientation!==6) throw Error('Expected orientation 6.');
const deck=createPresentation({size:{width:960,height:540}});
for(const [id,bytes,width,height] of [['exif',jpeg,300,200],['normalized',png,200,300]]) deck.registerAsset({id,kind:'image',source:{type:'bytes',value:bytes},width,height});
const slide=deck.addSlide({id:'orientation'});
slide.addElement({type:'text',id:'title',content:'EXIF 6 / normalized control',box:{x:40,y:25,width:850,height:60}});
for(const [id,x] of [['exif',100],['normalized',500]]) slide.addElement({type:'image',id:`image-${id}`,assetId:id,fit:'stretch',box:{x,y:120,width:200,height:300}});
const output=await generatePptx(deck,{jpegOrientationDiagnostics:'warn'});
if(output.warnings.length!==1 || output.warnings[0].code!=='jpeg-exif-orientation-unverified') throw Error('Unexpected warning.');
const preview=await renderPresentationToSvg(deck),hash=b=>createHash('sha256').update(b).digest('hex');
await writeFile(join(dir,'candidate.pptx'),output.bytes);await writeFile(join(dir,'preview.svg'),preview.slides[0].svg);
await writeFile(join(dir,'producer.json'),JSON.stringify({jpegSha256:hash(jpeg),pngSha256:hash(png),pptxSha256:hash(output.bytes),svgSha256:hash(preview.slides[0].svg),info,warnings:output.warnings},null,2)+'\n');
console.log(JSON.stringify({dir,info,pptxSha256:hash(output.bytes)}));
