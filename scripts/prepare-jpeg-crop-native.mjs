import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { createHash } from "node:crypto";
import { createPresentation } from "../packages/core/dist/index.js";
import { generatePptx, orientJpegCrop } from "../packages/pptx-exporter/dist/index.js";
const dir = process.argv[2]; if (!dir || process.argv.length !== 3) throw Error("Expected sample directory.");
const png = await readFile(join(dir, "browser-normalized.png")), control = await readFile(join(dir, "crop-control.png"));
const deck = createPresentation({ size: { width: 960, height: 540 } });
deck.registerAsset({ id:"oriented", kind:"image", source:{type:"bytes",value:png}, mimeType:"image/png", width:200, height:300 });
deck.registerAsset({ id:"control", kind:"image", source:{type:"bytes",value:control}, mimeType:"image/png", width:200, height:200 });
const slide = deck.addSlide({id:"crop"});
slide.addElement({type:"text",id:"title",content:"EXIF 6 mapped crop / physical crop control",box:{x:40,y:25,width:880,height:60}});
const crop = orientJpegCrop({left:0,top:0,right:1/3,bottom:0},6);
slide.addElement({type:"image",id:"mapped",assetId:"oriented",fit:"crop",crop,box:{x:120,y:130,width:240,height:240}});
slide.addElement({type:"image",id:"control",assetId:"control",fit:"stretch",box:{x:600,y:130,width:240,height:240}});
const result = await generatePptx(deck); if (result.warnings.length) throw Error(JSON.stringify(result.warnings));
const hash = value => createHash("sha256").update(value).digest("hex");
await writeFile(join(dir,"crop-candidate.pptx"),result.bytes);
await writeFile(join(dir,"crop-producer.json"),JSON.stringify({crop,pptxSha256:hash(result.bytes),normalizedSha256:hash(png),controlSha256:hash(control),warnings:result.warnings},null,2)+"\n");
console.log(JSON.stringify({crop,sha256:hash(result.bytes)}));
